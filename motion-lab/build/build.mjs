// Assembles the HyperFrames project from build/src + build/timeline.json.
//   node build/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { planSvg } from "./gen-plan.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const LAB = path.resolve(HERE, "..");
const CMP = path.join(LAB, "composition");
const SRC = path.join(HERE, "src");
const cfg = JSON.parse(fs.readFileSync(path.join(HERE, "timeline.json"), "utf8"));

const fps = cfg.fps;
const beat = 60 / cfg.bpm;
const b2s = (b) => Math.round(b * beat * 1e6) / 1e6;
const total = b2s(cfg.beatsTotal);

// ---- photo treatment (media-use "resample before you scale") ----
// hero-aerial is only 1730 px wide but is shown at 1.12-1.16 x. Upscaling it once with Lanczos (+ a light luma unsharp) and letting the browser
// DOWNscale it to its 1730 px layout box gives cleaner edges than the browser upscaling the original. The original stays in build/assets-src.
{
  const src = path.join(HERE, "assets-src", "hero-aerial.jpg");
  const out = path.join(CMP, "assets", "img", "hero-aerial.jpg");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const r = spawnSync("ffmpeg", ["-v", "error", "-y", "-i", src, "-vf", "scale=2595:990:flags=lanczos,unsharp=5:5:0.6:5:5:0", "-q:v", "2", out], { encoding: "utf8" });
  if (r.status !== 0) throw new Error("ffmpeg photo treatment failed: " + r.stderr);
  fs.copyFileSync(path.join(HERE, "assets-src", "aerial-outlined.jpg"), path.join(CMP, "assets", "img", "aerial-outlined.jpg"));
}

// ---- clock ----
const scenes = cfg.scenes.map((s) => {
  const boundary = b2s(s.boundaryBeat);
  const end = b2s(s.endBeat);
  const start = Math.round((boundary - s.lead) * 1e6) / 1e6;
  return { id: s.id, file: s.file, transition: s.transition, boundary, end, start, dur: Math.round((end - start) * 1e6) / 1e6, lead: s.lead };
});
const hosts = Object.fromEntries(scenes.map((s) => [s.id, s]));
const ev = {};
for (const [k, v] of Object.entries(cfg.events)) ev[k] = v.beat !== undefined ? b2s(v.beat) : v.sec;
// seam.<scene> = the moment the transition into that scene begins (host start)
for (const s of scenes) if (s.lead > 0) ev["seam." + s.id] = s.start;
// generated clock (read by build/qa.sh to pick seam frames)
fs.writeFileSync(path.join(HERE, "clock.json"), JSON.stringify({ fps, bpm: cfg.bpm, beat, total, hosts, ev }, null, 2));

const timelineJs = `// generated by build/build.mjs from build/timeline.json. Do not edit.
window.TL = ${JSON.stringify({ fps, bpm: cfg.bpm, beat, total, wipe: cfg.wipeSeconds, dissolve: cfg.dissolveSeconds, scenes, hosts, ev }, null, 2)};
`;
fs.mkdirSync(path.join(CMP, "assets"), { recursive: true });
fs.writeFileSync(path.join(CMP, "assets", "timeline.js"), timelineJs);

// ---- shared snippets ----
const commonCss = fs.readFileSync(path.join(SRC, "common.css"), "utf8");
const logoGlyph = `<svg viewBox="0 0 32 32" aria-hidden="true"><rect width="32" height="32" rx="7" fill="#1d3a3c"/><rect x="0.5" y="0.5" width="31" height="31" rx="6.5" fill="none" stroke="rgba(255,255,255,0.16)"/><path d="M6 10.5h20v11H6z" fill="none" stroke="#d4f0c9" stroke-width="1.6"/><path d="M6 16h20M11 10.5v11M16 10.5v11M21 10.5v11" stroke="#d4f0c9" stroke-width="1" stroke-opacity=".55"/><path d="M16 16h5v5.5h-5z" fill="#d4f0c9"/></svg>`;
const plan = planSvg({ widthPx: 1536 });
const unitW = 620;
const unitH = Math.round((unitW * 46) / 42.5);
const unitSvg = fs.readFileSync(path.join(SRC, "unit.svg.html"), "utf8").replace("{{W}}", String(unitW)).replace("{{H}}", String(unitH));

function inject(html, dur) {
  return html
    .replace("/*COMMON_CSS*/", commonCss)
    .replace("<!--PLAN_SVG-->", plan.svg)
    .replace("<!--UNIT_SVG-->", unitSvg)
    .replaceAll("{{LOGO_GLYPH}}", logoGlyph)
    .replaceAll("__DUR__", String(dur));
}

fs.mkdirSync(path.join(CMP, "compositions"), { recursive: true });
for (const s of scenes) {
  const p = path.join(SRC, `${s.file}.src.html`);
  if (!fs.existsSync(p)) {
    console.log("skip (no source yet):", s.file);
    continue;
  }
  const html = inject(fs.readFileSync(p, "utf8"), s.dur);
  fs.writeFileSync(path.join(CMP, "compositions", `${s.file}.html`), html);
  console.log("scene", s.file.padEnd(14), "start", s.start.toFixed(3), "end", s.end.toFixed(3), "dur", s.dur.toFixed(3));
}

// ---- index.html (silent film: no <audio> elements are emitted) ----
const round3 = (n) => Math.round(n * 1000) / 1000;
const ONLY = process.env.ONLY ? process.env.ONLY.split(",") : null;
const hostLines = scenes.filter((s) => !ONLY || ONLY.includes(s.id)).map((s, i) => `      <div id="h-${s.id}" class="scene" data-composition-id="${s.file}" data-composition-src="compositions/${s.file}.html" data-start="${round3(s.start)}" data-duration="${round3(s.dur)}" data-track-index="1" data-width="1920" data-height="1080" data-track-kind="graphics" style="z-index:${i + 1}"></div>`).join("\n");
let index = fs.readFileSync(path.join(SRC, "index.src.html"), "utf8");
index = index.replace("<!--HOSTS-->", hostLines).replace("__TOTAL__", String(total));
fs.writeFileSync(path.join(CMP, "index.html"), index);

console.log("index.html written; total", total, "s =", Math.round(total * fps), "frames (silent film, no audio elements)");
